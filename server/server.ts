#!/usr/bin/env bun
/**
 * voice-agent — dashboard page server (Bun).
 *
 * Web-only real-time speech-to-speech agent:
 *  - POST api/session  → mints a short-lived ephemeral token at the provider and
 *                        returns everything the browser needs to open the realtime
 *                        WebSocket directly (audio never flows through here).
 *  - POST api/calls/end→ closes a call-log entry written by the page.
 *  - GET  api/calls    → last 50 calls.
 *  - GET  api/status   → config state for the page banner (never returns the key).
 *  - GET  /            → single-page UI from the bundled index.html (labels follow
 *                        the browser language); never embedded in this file.
 *  - GET  /healthz
 *
 * Config comes from ~/.config/open-bot/plugin-<id>.json (settings + vault),
 * regenerated by the control plane — never edited by hand.
 */

import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const PLUGIN_ID = process.env.OPEN_BOT_PLUGIN_ID || "voice-agent";
const PORT = Number(process.env.OPEN_BOT_PAGE_PORT ?? 4747);
const DATA_DIR = `/home/agent/.open-bot/pages-data/${PLUGIN_ID}`;
const CALLS_FILE = join(DATA_DIR, "calls.json");

type Cfg = { settings?: Record<string, string>; vault?: Record<string, string> };

function loadConfig(): Cfg {
  try {
    return JSON.parse(readFileSync(`/home/agent/.config/open-bot/plugin-${PLUGIN_ID}.json`, "utf8")) as Cfg;
  } catch {
    return {};
  }
}

function settings(): Record<string, string> {
  return loadConfig().settings ?? {};
}

function vault(): Record<string, string> {
  return loadConfig().vault ?? {};
}

/** A secret can come from the Plugins-page setting first, the plugin vault slug,
 *  or the shared provider key (Config page Keys tab, slug "xai") — whichever exists.
 *  Pasted keys often carry line wraps or stray spaces: strip all whitespace. */
function cleanKey(v: unknown): string {
  return String(v ?? "").replace(/\s+/g, "");
}

function secretOf(): string {
  const s = settings();
  const v = vault();
  return (
    cleanKey(s.xai_api_key) ||
    cleanKey(v["xai-api-key"]) ||
    cleanKey(v["xai"])
  );
}

function keySource(): string {
  const s = settings();
  const v = vault();
  if (cleanKey(s.xai_api_key)) return "settings";
  if (cleanKey(v["xai-api-key"])) return "vault";
  if (cleanKey(v["xai"])) return "shared:xai";
  return "";
}

function conf() {
  const s = settings();
  const key = secretOf();
  const provider = (s.provider || "xai").trim();
  const model = (s.model || "grok-voice-latest").trim();
  const voice = (s.voice || "eve").trim();
  const instructions = (s.instructions || "").trim();
  const gateway = (s.gateway_base || "").trim().replace(/\/+$/, "");
  return { provider, model, voice, instructions, gateway, hasKey: Boolean(key) };
}

function providerBase(gateway: string, provider: string): string {
  if (gateway) return gateway;
  if (provider === "xai") return "https://api.x.ai";
  return "https://api.x.ai";
}

function toWsBase(httpBase: string): string {
  if (/^https:\/\//i.test(httpBase)) return "wss://" + httpBase.slice(8);
  if (/^http:\/\//i.test(httpBase)) return "ws://" + httpBase.slice(7);
  return httpBase;
}

/* ---------------- call log ---------------- */

type CallEntry = {
  id: string;
  ts: string;
  provider: string;
  model: string;
  voice: string;
  durationSec?: number;
  userTurns?: number;
  agentTurns?: number;
  ended?: boolean;
};

const DEFAULT_CAPABILITIES =
  "search the web and read pages, automate a desktop browser, read and write files on the desktop, generate images and videos, build 3D models, write and run code, create schedules and recurring jobs, and use installed plugins (price watching, shared calendar, Facebook messages guardian, news trading, web search). It cannot make phone calls or access accounts the user has not connected.";

function loadCalls(): CallEntry[] {
  try {
    return JSON.parse(readFileSync(CALLS_FILE, "utf8")) as CallEntry[];
  } catch {
    return [];
  }
}

function saveCalls(list: CallEntry[]) {
  try {
    if (!existsSync(DATA_DIR)) mkdirSync(DATA_DIR, { recursive: true });
    writeFileSync(CALLS_FILE, JSON.stringify(list.slice(-500), null, 1));
  } catch {}
}

/* ---------------- provider calls ---------------- */

async function mintToken(base: string, key: string): Promise<{ token: string; raw: unknown; status: number }> {
  const res = await fetch(base + "/v1/realtime/client_secrets", {
    method: "POST",
    headers: { Authorization: `Bearer ${key}`, "Content-Type": "application/json" },
    body: JSON.stringify({ expires_after: { seconds: 300 } }),
  });
  const text = await res.text();
  let raw: unknown = text;
  try {
    raw = JSON.parse(text);
  } catch {}
  const j = raw as Record<string, any>;
  const token =
    j?.value ?? j?.token ?? j?.client_secret?.value ?? j?.client_secret?.token ?? j?.ephemeral_token ?? j?.secret ?? "";
  return { token: String(token ?? ""), raw, status: res.status };
}

/* ---------------- UI routing (directive 2026-10-16) ---------------- */

// The UI lives in real files next to this server (index.html + app.ts + styles.css).
// Frozen install (marketplace): the control plane bundles the UI and hands the
// bundle over via OPEN_BOT_PAGE_UI. Local checkout / preview (bun --hot): import
// the HTML and let Bun bundle it. The server never embeds or reads the HTML itself.
const HTML_HEADERS = { "content-type": "text/html; charset=utf-8", "cache-control": "no-cache" };
const routes: Record<string, unknown> = process.env.OPEN_BOT_PAGE_UI
  ? { "/": () => new Response(Bun.file(process.env.OPEN_BOT_PAGE_UI as string), { headers: HTML_HEADERS }) }
  : await import("./index.html").then((m) => {
      // Local checkout / preview: Bun bundles the HTML (app.ts + styles.css) on import.
      // The HTMLBundle must be handed to routes as-is, never wrapped in new Response().
      return { "/": m.default, "/index.html": m.default };
    });

/* ---------------- server ---------------- */

function json(res: unknown, status = 200): Response {
  return new Response(JSON.stringify(res), { status, headers: { "content-type": "application/json" } });
}

async function body<T>(req: Request): Promise<T | null> {
  try {
    return (await req.json()) as T;
  } catch {
    return null;
  }
}

Bun.serve({
  port: PORT,
  routes,
  async fetch(req) {
    const url = new URL(req.url);
    const p = url.pathname.replace(/\/+$/, "") || "/";

    if (p === "/healthz") return new Response("ok");

    if (p === "/api/status") {
      const c = conf();
      const calls = loadCalls();
      return json({
        plugin: PLUGIN_ID,
        provider: c.provider,
        model: c.model,
        voice: c.voice,
        hasKey: c.hasKey,
        keySource: keySource(),
        callsCount: calls.length,
      });
    }

    if (p === "/api/session" && req.method === "POST") {
      const c = conf();
      const key = secretOf();
      if (!key) {
        return json({ error: "missing_key", hint: "Plugins tab → Voice Agent → Settings: set the xAI API key or fill vault slug xai-api-key." }, 400);
      }
      const base = providerBase(c.gateway, c.provider);
      try {
        const mint = await mintToken(base, key);
        if (!mint.token) {
          return json({ error: "token", detail: String(mint.status) + " " + JSON.stringify(mint.raw).slice(0, 300) }, 502);
        }
        const id = crypto.randomUUID();
        const calls = loadCalls();
        calls.push({ id, ts: new Date().toISOString(), provider: c.provider, model: c.model, voice: c.voice });
        saveCalls(calls);
        const wsUrl = toWsBase(base) + "/v1/realtime?model=" + encodeURIComponent(c.model);
        const capabilities = (settings().capabilities || DEFAULT_CAPABILITIES).trim();
        const tools = [
          {
            type: "function",
            name: "delegate_openbot",
            description:
              "Delegate a task to the user's open-bot desktop agent. It can: " +
              capabilities +
              " Use it whenever the caller asks for something that needs real actions or live information; pass a clear, self-contained task in the caller's language.",
            parameters: {
              type: "object",
              properties: { task: { type: "string", description: "The task for the desktop agent, self-contained" } },
              required: ["task"],
            },
          },
        ];
        return json({
          sessionId: id,
          token: mint.token,
          wsUrl,
          provider: c.provider,
          model: c.model,
          voice: c.voice,
          instructions: c.instructions,
          tools,
        });
      } catch (e) {
        return json({ error: "net", detail: String(e).slice(0, 200) }, 502);
      }
    }

    if (p === "/api/delegate" && req.method === "POST") {
      const b = await body<{ task?: string }>(req);
      const task = String(b?.task ?? "").trim().slice(0, 2000);
      if (!task) return json({ error: "bad_request" }, 400);
      if (!existsSync(DATA_DIR)) mkdirSync(DATA_DIR, { recursive: true });
      const id = crypto.randomUUID();
      writeFileSync(join(DATA_DIR, `delegate-task-${id}.json`), JSON.stringify({ task }));
      const bin = `/usr/local/bin/ob-plugin-${PLUGIN_ID}-delegate-worker`;
      const local = join(import.meta.dir, "delegate-worker");
      const cmd = existsSync(bin) ? [bin, id] : ["bun", local, id];
      try {
        Bun.spawn(["setsid", ...cmd], { stdin: "ignore", stdout: "ignore", stderr: "ignore", cwd: "/home/agent/workspace" });
      } catch {
        try {
          Bun.spawn(cmd, { stdin: "ignore", stdout: "ignore", stderr: "ignore" });
        } catch {}
      }
      return json({ id }, 202);
    }

    if (p === "/api/delegate" && req.method === "GET") {
      const id = String(url.searchParams.get("id") ?? "");
      if (!/^[0-9a-f-]{10,40}$/.test(id)) return json({ error: "bad_request" }, 400);
      try {
        const r = JSON.parse(readFileSync(join(DATA_DIR, `delegate-result-${id}.json`), "utf8"));
        try {
          unlinkSync(join(DATA_DIR, `delegate-result-${id}.json`));
        } catch {}
        return json({ done: true, result: String(r.result ?? "") });
      } catch {
        return json({ done: false });
      }
    }

    if (p === "/api/calls/end" && req.method === "POST") {
      const b = await body<{ id?: string; durationSec?: number; userTurns?: number; agentTurns?: number }>(req);
      if (!b?.id) return json({ error: "bad_request" }, 400);
      const calls = loadCalls();
      const entry = calls.find((x) => x.id === b.id);
      if (entry) {
        const clamp = (v: unknown, lo: number, hi: number, d: number) => {
          const n = Math.round(Number(v ?? d));
          if (!Number.isFinite(n)) return d;
          return Math.min(hi, Math.max(lo, n));
        };
        entry.durationSec = clamp(b.durationSec, 0, 86400, 0);
        entry.userTurns = clamp(b.userTurns, 0, 10000, 0);
        entry.agentTurns = clamp(b.agentTurns, 0, 10000, 0);
        entry.ended = true;
        saveCalls(calls);
      }
      return json({ ok: true });
    }

    if (p === "/api/calls") {
      return json({ calls: loadCalls().slice(-50).reverse() });
    }

    return new Response("not found", { status: 404 });
  },
});

console.log(`voice-agent page server on :${PORT}`);
